import { Link, useParams, useSearchParams } from "react-router-dom";
import { useHost, useLatest, useSeries } from "../../api/hooks";
import type { Host, MetricSample } from "../../api/types";
import { PageHeader } from "../../components/PageHeader";
import { EmptyState, ErrorState, Loading } from "../../components/states/States";
import { StaleBanner } from "../../components/ui/Banners";
import { HealthBadge, SourceBadge } from "../../components/ui/Badges";
import { TimeSeriesChart } from "../../components/ui/TimeSeriesChart";
import { UtilCell } from "../../components/ui/UtilCell";
import { DASH, ago, bytesPerSecond, timestamp } from "../../lib/format";
import { METRICS, metricDef, type MetricDef } from "../../lib/metrics";
import { globalSearch, RANGES, useTimeRange } from "../../lib/timeRange";

const REPORTING = { reporting: "Reporting", silent: "Silent: no telemetry recently", replay: "Replay: history, not live" } as const;
const SOURCE_NOTE = {
  live: null,
  synthetic: "Synthetic host: generated by the simulator. These are not measurements of real infrastructure.",
  replay: "Replay host: stored history being replayed. Values are not current observations of live infrastructure.",
} as const;

export function HostDetailPage() {
  const { hostId = "" } = useParams();
  const [params] = useSearchParams();
  const host = useHost(hostId);
  const back = `/hosts${globalSearch(params)}`;

  if (host.isPending) return (<><PageHeader title={hostId} /><Loading label="Loading host" /></>);
  if (!host.data) return (<><PageHeader title={hostId} actions={<Link className="btn" to={back}>All hosts</Link>} /><ErrorState error={host.error} onRetry={() => host.refetch()} /></>);
  const h = host.data;

  return (
    <>
      <PageHeader title={h.hostname} subtitle={h.hostname !== h.host_id ? h.host_id : undefined} actions={<Link className="btn" to={back}>All hosts</Link>} />
      <StaleBanner failed={host.isError} updatedAt={host.dataUpdatedAt} onRetry={() => host.refetch()} />
      {SOURCE_NOTE[h.source] && <div className={`banner src-note src-note-${h.source}`} role="note"><SourceBadge source={h.source} /> {SOURCE_NOTE[h.source]}</div>}
      <Identity h={h} />
      <Current host={h} />
      <History host={h} />
    </>
  );
}

function Identity({ h }: { h: Host }) {
  return (
    <div className="grid2">
      <section className="widget" aria-label="Host identity">
        <div className="widget-head"><h2>Identity</h2><SourceBadge source={h.source} /></div>
        <div className="widget-body">
          <dl className="kv">
            <dt>Host id</dt><dd className="mono">{h.host_id}</dd>
            <dt>Service</dt><dd>{h.service ?? <span className="dim">{DASH} not reported</span>}</dd>
            <dt>Agent</dt><dd className="mono">{h.agent_id}</dd>
            <dt>Reporting</dt><dd>{REPORTING[h.reporting_status]}</dd>
            <dt>First seen</dt><dd className="mono" title={h.first_seen}>{timestamp(h.first_seen)}</dd>
            <dt>Last seen</dt><dd><span className="mono" title={h.last_seen}>{timestamp(h.last_seen)}</span> <span className="dim">({ago(h.last_seen_age_seconds)})</span></dd>
          </dl>
        </div>
      </section>
      <section className="widget" aria-label="Health">
        <div className="widget-head"><h2>Health</h2><HealthBadge status={h.health.status} /></div>
        <div className="widget-body">
          {h.health.reasons.length > 0 ? (
            <ul className="reasons">
              {h.health.reasons.map((r, i) => (
                <li key={i}><span className={`lvl lvl-${r.level}`}>{r.level.toUpperCase()}</span> {r.metric.replace("system.", "").replace(".utilization", "")}{r.labels.mount ? ` (${r.labels.mount})` : ""} is <span className="mono">{r.value.toFixed(1)}%</span>, at or above {r.threshold}%</li>
              ))}
            </ul>
          ) : h.health.status === "offline" ? (
            <p>No telemetry received for {ago(h.last_seen_age_seconds).replace(" ago", "")}, so the host is considered offline.</p>
          ) : h.health.status === "unknown" ? (
            <p>There is no fresh CPU, memory or disk measurement to evaluate, so health cannot be judged.</p>
          ) : (
            <p>All evaluated metrics are below their warning thresholds.</p>
          )}
        </div>
      </section>
    </div>
  );
}

function Tile({ label, children, sub }: { label: string; children: React.ReactNode; sub?: React.ReactNode }) {
  return <div className="tile"><span className="kpi-label">{label}</span><div className="tile-value">{children}</div>{sub && <div className="dim small">{sub}</div>}</div>;
}

/** Current observations: the latest endpoint only. A stale or missing sample is labelled, never zero. */
function Current({ host }: { host: Host }) {
  const q = useLatest(host.host_id);
  const samples = q.data?.metrics ?? [];
  const of = (name: string) => samples.filter((s) => s.name === name);
  const gauge = (name: string) => of(name)[0];
  const asOf = (s?: MetricSample) => (s ? `observed ${timestamp(s.observed_at)}` : undefined);
  const Gauge = ({ s }: { s?: MetricSample }) =>
    !s ? <span className="dim">{DASH} not reported</span> : s.stale ? <span className="dim">{DASH} stale</span> : <UtilCell value={s.value} />;

  return (
    <section aria-label="Current values" className="stack-gap">
      <h2 className="section-h">Current observations <span className="dim">latest sample from the agent{host.source !== "live" ? ` · ${host.source} data, not live` : ""}</span></h2>
      {q.isPending && <Loading label="Loading latest metrics" />}
      {q.isError && !q.data && <ErrorState error={q.error} onRetry={() => q.refetch()} />}
      {q.data && (
        <>
          <StaleBanner failed={q.isError} updatedAt={q.dataUpdatedAt} onRetry={() => q.refetch()} />
          <div className="tiles">
            <Tile label="CPU" sub={asOf(gauge("system.cpu.utilization"))}><Gauge s={gauge("system.cpu.utilization")} /></Tile>
            <Tile label="Memory" sub={asOf(gauge("system.memory.utilization"))}><Gauge s={gauge("system.memory.utilization")} /></Tile>
            {of("system.disk.utilization").length === 0 ? (
              <Tile label="Disk"><span className="dim">{DASH} not reported</span></Tile>
            ) : (
              of("system.disk.utilization").map((s) => (
                <Tile key={s.labels.mount ?? "disk"} label={`Disk ${s.labels.mount ?? ""}`} sub={asOf(s)}><Gauge s={s} /></Tile>
              ))
            )}
            <NetTile dir="rx" samples={of("system.network.rx_bytes")} />
            <NetTile dir="tx" samples={of("system.network.tx_bytes")} />
          </div>
          <p className="dim small">Disk I/O and per-process metrics are not collected by the agent (telemetry contract v1), so they are not shown.</p>
        </>
      )}
    </section>
  );
}

/** Network throughput is the backend-derived rate_per_second from two consecutive samples; the raw cumulative counter is never shown as a rate. */
function NetTile({ dir, samples }: { dir: "rx" | "tx"; samples: MetricSample[] }) {
  const label = dir === "rx" ? "Network receive" : "Network transmit";
  const fresh = samples.filter((s) => !s.stale);
  const rated = fresh.filter((s) => s.rate_per_second != null);
  if (samples.length === 0) return <Tile label={label}><span className="dim">{DASH} not reported</span></Tile>;
  if (rated.length === 0) {
    return <Tile label={label} sub="A rate needs two consecutive valid samples (none yet, the counter reset, or samples were missed)."><span className="dim">{DASH} rate unavailable</span></Tile>;
  }
  const total = rated.reduce((a, s) => a + (s.rate_per_second ?? 0), 0);
  return (
    <Tile label={label} sub={rated.map((s) => `${s.labels.interface ?? "?"} ${bytesPerSecond(s.rate_per_second)}`).join(" · ")}>
      <span className="mono big">{bytesPerSecond(total)}</span>
    </Tile>
  );
}

function History({ host }: { host: Host }) {
  const { range } = useTimeRange();
  const label = RANGES.find((r) => r.id === range)?.label ?? range;
  return (
    <section aria-label="History" className="stack-gap">
      <h2 className="section-h">History <span className="dim">last {label} · change the range in the top bar</span></h2>
      <div className="grid2">
        {METRICS.map((m) => <HistoryChart key={m.name} host={host} metric={m} range={range} />)}
      </div>
    </section>
  );
}

function HistoryChart({ host, metric, range }: { host: Host; metric: MetricDef; range: ReturnType<typeof useTimeRange>["range"] }) {
  const q = useSeries(host.host_id, metric.name, range, "avg");
  const d = q.data;
  const hasPoints = !!d && d.series.some((s) => s.points.some((p) => p.value != null));
  return (
    <section className="widget" aria-label={`${metric.label} history`}>
      <div className="widget-head"><h2>{metric.label}</h2><span className="dim mono">{d ? `${d.agg} · ${d.step_seconds}s buckets` : ""}</span></div>
      <div className="widget-body">
        {q.isPending && <Loading label={`Loading ${metric.label}`} />}
        {q.isError && !d && <ErrorState error={q.error} onRetry={() => q.refetch()} />}
        {d && !hasPoints && (
          <EmptyState
            title={`No ${metric.label.toLowerCase()} data`}
            body={`This host reported no ${metricDef(metric.name)?.label.toLowerCase()} samples in this window (last seen ${timestamp(host.last_seen)}).${host.source === "replay" ? " Replayed history may lie outside the selected range." : ""}`}
          />
        )}
        {d && hasPoints && <TimeSeriesChart series={d.series} unit={metric.unit} start={d.start} end={d.end} label={`${metric.label} over the last ${range}`} height={170} />}
        {metric.note && hasPoints && <p className="dim small">{metric.note}</p>}
      </div>
    </section>
  );
}
