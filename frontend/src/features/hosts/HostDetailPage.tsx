/** Alerts for this host only: the alert list filtered by host_id on the server. Never filtered from a fleet-wide list. */
function HostAlerts({ host, carry }: { host: Host; carry: string }) {
  const q = useAlerts("all", ALERT_LIMIT, host.host_id);
  const m = useAlertMutations();
  const split = q.data ? splitHostAlerts(q.data.alerts, RESOLVED_SHOWN) : null;
  const capped = q.data ? alertsCapped(q.data.alerts.length, q.data.total) : false;
  const { range } = useTimeRange();
  const rangeDef = RANGES.find((r) => r.id === range) ?? RANGES[1]!;
  return (
    <section className="widget" aria-label="Alerts for this host" id="alerts">
      <div className="widget-head"><h2>Alerts</h2><span className="dim mono">{q.data ? `${q.data.total} recorded` : ""}</span></div>
      <div className="widget-body">
        {q.isPending && <Loading label="Loading alerts for this host" />}
        {q.isError && !q.data && <ErrorState error={q.error} onRetry={() => q.refetch()} />}
        <StaleBanner failed={q.isError && !!q.data} updatedAt={q.dataUpdatedAt} onRetry={() => q.refetch()} />
        {capped && <PartialBanner>Showing the {q.data!.alerts.length} most recent of {q.data!.total} alerts for this host.</PartialBanner>}
        {m.acknowledge.isError && <p className="banner warn" role="alert">Could not acknowledge the alert. Nothing was changed.</p>}
        {q.data && <AlertTimeline alerts={q.data.alerts} rangeMs={rangeDef.ms} label={rangeDef.label} capped={capped} />}
        {split && split.active.length === 0 && split.resolved.length === 0 && (
          <p className="dim">No alerts have been recorded for this host.</p>
        )}
        {split && split.active.length === 0 && split.resolved.length > 0 && (
          <p className="dim">No active alerts for this host.</p>
        )}
      </div>
      {split && split.active.length > 0 && (
        <div className="alert-group alert-active" aria-label="Active alerts for this host">
          <h3 className="small">Active</h3>
          <table className="tbl">
            <thead><tr><th>Severity</th><th>Condition</th><th>State</th><th>Triggered</th><th><span className="sr-only">Actions</span></th></tr></thead>
            <tbody>
              {split.active.map((a: Alert) => (
                <tr key={a.id}>
                  <td><HealthBadge status={a.severity as "critical" | "warning"} /></td>
                  <td className="small">{conditionText(a)}</td>
                  <td className="small">{acknowledgementText(a)}</td>
                  <td className="small dim" title={a.opened_at}>{timestamp(a.opened_at)}</td>
                  <td className="small">
                    <div className="row-actions">
                      {a.state === "open" && (
                        <button type="button" className="btn" disabled={m.acknowledge.isPending} aria-label={`Acknowledge alert ${conditionText(a)}`} onClick={() => m.acknowledge.mutate(a.id)}>Acknowledge</button>
                      )}
                      <Link to={`/alerts/${encodeURIComponent(a.id)}${carry}`}>Investigate</Link>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
      {split && split.resolved.length > 0 && (
        <div className="alert-group alert-resolved" aria-label="Recently resolved alerts for this host">
          <h3 className="small dim">Recently resolved</h3>
          <table className="tbl dim">
            <thead><tr><th>Severity</th><th>Condition</th><th>Resolution</th><th>Resolved</th><th><span className="sr-only">Actions</span></th></tr></thead>
            <tbody>
              {split.resolved.map((a: Alert) => (
                <tr key={a.id}>
                  <td><HealthBadge status={a.severity as "critical" | "warning"} /></td>
                  <td className="small">{conditionText(a)}</td>
                  <td className="small">{resolutionText(a)}</td>
                  <td className="small" title={a.resolved_at ?? undefined}>{a.resolved_at ? timestamp(a.resolved_at) : DASH}</td>
                  <td className="small"><Link to={`/alerts/${encodeURIComponent(a.id)}${carry}`}>Investigate</Link></td>
                </tr>
              ))}
            </tbody>
          </table>
          {split.resolvedHidden > 0 && <p className="dim small">{split.resolvedHidden} older resolved alerts are not shown here.</p>}
        </div>
      )}
    </section>
  );
}

const TIMELINE_BUCKETS = 24;
const SEVERITY_FILL = { critical: "#e5483a", warning: "#e0951f" } as const;

/**
 * Alerts opened for this host per bucket over the selected range. Built only from the loaded alerts: when the list is capped,
 * the caption says so, because older alerts in the range may be missing.
 */
function AlertTimeline({ alerts, rangeMs, label, capped }: { alerts: Alert[]; rangeMs: number; label: string; capped: boolean }) {
  const now = Date.now();
  const start = now - rangeMs;
  const width = rangeMs / TIMELINE_BUCKETS;
  const bins = Array.from({ length: TIMELINE_BUCKETS }, () => ({ critical: 0, warning: 0 }));
  let inRange = 0;
  for (const a of alerts) {
    const t = Date.parse(a.opened_at);
    if (t < start || t > now) continue;
    inRange++;
    const i = Math.min(TIMELINE_BUCKETS - 1, Math.floor((t - start) / width));
    bins[i]![a.severity === "critical" ? "critical" : "warning"]++;
  }
  const max = Math.max(1, ...bins.map((b) => b.critical + b.warning));
  return (
    <figure className="host-timeline" aria-label={`Alerts opened for this host in the last ${label}`}>
      {inRange === 0 ? (
        <p className="dim small">No alert opened for this host in the last {label}{capped ? " among the loaded alerts" : ""}.</p>
      ) : (
        <svg viewBox={`0 0 ${TIMELINE_BUCKETS * 10} 60`} preserveAspectRatio="none" role="img" aria-label={`${inRange} alerts opened in the last ${label}`} className="host-timeline-svg">
          {bins.map((b, i) => {
            const hc = (b.critical / max) * 56;
            const hw = (b.warning / max) * 56;
            return (
              <g key={i}>
                {hc > 0 && <rect x={i * 10 + 1} y={60 - hc} width={8} height={hc} fill={SEVERITY_FILL.critical} />}
                {hw > 0 && <rect x={i * 10 + 1} y={60 - hc - hw} width={8} height={hw} fill={SEVERITY_FILL.warning} />}
              </g>
            );
          })}
        </svg>
      )}
      <figcaption className="dim small">
        {inRange} opened in the last {label}, per {Math.round(width / 60_000)} min buckets, from the loaded alerts for this host.
        {capped && " The list is capped at the most recent alerts, so older bars may be incomplete."}
      </figcaption>
    </figure>
  );
}

/** A host that is registered but has never sent telemetry: it has no host page data, so the registry is the only source. */
function NeverReported({ hostId }: { hostId: string }) {
  const reg = useRegistryHosts();
  if (reg.isPending) return <Loading label="Checking the registry" />;
  const row: RegistryHost | undefined = reg.data?.find((r) => r.host_id === hostId);
  if (row && row.telemetry_state === "awaiting_first_telemetry") {
    return (
      <EmptyState title="Registered, no telemetry yet" body={`This host was registered on ${timestamp(row.created_at)}, with ${row.active_credentials} active credential${row.active_credentials === 1 ? "" : "s"}. It has never reported, so there are no metrics or health to show.`}>
        <Link to="/settings/agents">Open Agents to check the install</Link>
      </EmptyState>
    );
  }
  return <ErrorState error={new ApiError(404, "host_not_found", "Host not found")} />;
}

function Tile({ label, children, sub }: { label: string; children: React.ReactNode; sub?: React.ReactNode }) {
  return <div className="tile"><span className="kpi-label">{label}</span><div className="tile-value">{children}</div>{sub && <div className="dim small">{sub}</div>}</div>;
}

/** Current observations: the latest endpoint only. Colour comes from the configured limit for the metric; missing, stale or unjudged values have no state colour. */
function Current({ host, thresholds }: { host: Host; thresholds: ThresholdState }) {
  const q = useLatest(host.host_id);
  const samples = q.data?.metrics ?? [];
  const of = (name: string) => samples.filter((s) => s.name === name);
  const gauge = (name: string) => of(name)[0];
  const asOf = (s?: MetricSample) => (s ? `observed ${timestamp(s.observed_at)}` : undefined);
  const rules = thresholds.status === "loaded" ? thresholds.rules : undefined;
  const limitSub = (metric: string) => {
    if (thresholds.status === "loading") return "thresholds loading";
    if (thresholds.status === "error") return "thresholds unavailable";
    return thresholdText(ruleFor(rules, metric)) ?? "no configured limit";
  };
  const Gauge = ({ s, metric }: { s?: MetricSample; metric: string }) => {
    if (!s) return <span className="dim">{DASH} not reported</span>;
    if (s.stale) return <span className="dim">{DASH} stale</span>;
    const rule = ruleFor(rules, metric);
    return <UtilCell value={s.value} neutral={!rule} warn={rule?.warning ?? 0} crit={rule?.critical ?? 0} />;
  };

  return (
    <section aria-label="Current values" className="stack-gap">
      <h2 className="section-h">Current observations <span className="dim">latest sample from the agent{host.source !== "live" ? ` · ${host.source} data, not live` : ""}</span></h2>
      {thresholds.status === "error" && (
        <p className="banner notice" role="status">Thresholds could not be loaded, so these values are shown without a state. Nothing is judged against an assumed limit.</p>
      )}
      {q.isPending && <Loading label="Loading latest metrics" />}
      {q.isError && !q.data && <ErrorState error={q.error} onRetry={() => q.refetch()} />}
      {q.data && (
        <>
          <StaleBanner failed={q.isError} updatedAt={q.dataUpdatedAt} onRetry={() => q.refetch()} />
          <div className="tiles">
            <Tile label="CPU" sub={`${asOf(gauge("system.cpu.utilization")) ?? ""}${asOf(gauge("system.cpu.utilization")) ? " · " : ""}${limitSub("system.cpu.utilization")}`}>
              <Gauge s={gauge("system.cpu.utilization")} metric="system.cpu.utilization" />
            </Tile>
            <Tile label="Memory" sub={`${asOf(gauge("system.memory.utilization")) ?? ""}${asOf(gauge("system.memory.utilization")) ? " · " : ""}${limitSub("system.memory.utilization")}`}>
              <Gauge s={gauge("system.memory.utilization")} metric="system.memory.utilization" />
            </Tile>
            {of("system.disk.utilization").length === 0 ? (
              <Tile label="Disk"><span className="dim">{DASH} not reported</span></Tile>
            ) : (
              of("system.disk.utilization").map((s) => (
                <Tile key={s.labels.mount ?? "disk"} label={`Disk ${s.labels.mount ?? ""}`} sub={`${asOf(s) ?? ""}${asOf(s) ? " · " : ""}${limitSub("system.disk.utilization")}`}>
                  <Gauge s={s} metric="system.disk.utilization" />
                </Tile>
              ))
            )}
            <NetTile dir="rx" samples={of("system.network.rx_bytes")} />
            <NetTile dir="tx" samples={of("system.network.tx_bytes")} />
          </div>
          <p className="dim small">Disk I/O and per-process metrics are not collected by the agent (telemetry contract v1), so they are not shown.</p>
        </>
      )}
    </section>
  );
}

/** Network throughput is the backend-derived rate_per_second from two consecutive samples; the raw cumulative counter is never shown as a rate. */
function NetTile({ dir, samples }: { dir: "rx" | "tx"; samples: MetricSample[] }) {
  const label = dir === "rx" ? "Network receive" : "Network transmit";
  const fresh = samples.filter((s) => !s.stale);
  const rated = fresh.filter((s) => s.rate_per_second != null);
  if (samples.length === 0) return <Tile label={label}><span className="dim">{DASH} not reported</span></Tile>;
  if (rated.length === 0) {
    return <Tile label={label} sub="A rate needs two consecutive valid samples (none yet, the counter reset, or samples were missed)."><span className="dim">{DASH} rate unavailable</span></Tile>;
  }
  const total = rated.reduce((a, s) => a + (s.rate_per_second ?? 0), 0);
  return (
    <Tile label={label} sub={rated.map((s) => `${s.labels.interface ?? "?"} ${bytesPerSecond(s.rate_per_second)}`).join(" · ")}>
      <span className="mono big">{bytesPerSecond(total)}</span>
    </Tile>
  );
}

function History({ host, thresholds }: { host: Host; thresholds: ThresholdState }) {
  const { range } = useTimeRange();
  const label = RANGES.find((r) => r.id === range)?.label ?? range;
  const rules = thresholds.status === "loaded" ? thresholds.rules : undefined;
  return (
    <section aria-label="History" id="history" className="stack-gap">
      <h2 className="section-h">History <span className="dim">last {label} · change the range in the top bar</span></h2>
      <div className="grid2">
        {METRICS.map((m) => <HistoryChart key={m.name} host={host} metric={m} range={range} rule={ruleFor(rules, m.name)} />)}
        <NotCollected label="Disk I/O" />
        <NotCollected label="Process count" />
      </div>
    </section>
  );
}

/** A metric the agent does not send (telemetry contract v1). Shown so its absence is explicit, never a blank chart. */
function NotCollected({ label }: { label: string }) {
  return (
    <section className="widget" aria-label={`${label} history`}>
      <div className="widget-head"><h2>{label}</h2><span className="dim mono">not collected</span></div>
      <div className="widget-body">
        <p className="dim">Not available: the agent does not collect {label.toLowerCase()} in telemetry contract v1, so there is no history to show.</p>
      </div>
    </section>
  );
}

function HistoryChart({ host, metric, range, rule }: { host: Host; metric: MetricDef; range: ReturnType<typeof useTimeRange>["range"]; rule: { warning: number; critical: number } | undefined }) {
  const q = useSeries(host.host_id, metric.name, range, "avg");
  const d = q.data;
  const hasPoints = !!d && d.series.some((s) => s.points.some((p) => p.value != null));
  return (
    <section className="widget" aria-label={`${metric.label} history`}>
      <div className="widget-head"><h2>{metric.label}</h2><span className="dim mono">{d ? `${d.agg} · ${d.step_seconds}s buckets` : ""}</span></div>
      <div className="widget-body">
        {q.isPending && <Loading label={`Loading ${metric.label}`} />}
        {q.isError && !d && <ErrorState error={q.error} onRetry={() => q.refetch()} />}
        {d && !hasPoints && (
          <EmptyState
            title={`No ${metric.label.toLowerCase()} data`}
            body={`This host reported no ${metricDef(metric.name)?.label.toLowerCase()} samples in this window (last seen ${timestamp(host.last_seen)}).${host.source === "replay" ? " Replayed history may lie outside the selected range." : ""}`}
          />
        )}
        {d && hasPoints && (
          <TimeSeriesChart
            series={d.series} unit={metric.unit} start={d.start} end={d.end} label={`${metric.label} over the last ${range}`} height={170}
            threshold={metric.unit === "percent" && rule ? { value: rule.critical, label: `critical ${rule.critical}%` } : undefined}
          />
        )}
        {metric.note && hasPoints && <p className="dim small">{metric.note}</p>}
      </div>
    </section>
  );
}
