const REPORTING = { reporting: "Connected", stale: "Stale: telemetry is late", silent: "Offline: no telemetry recently", replay: "Replay: history, not live" } as const;
const REPORTING_SHORT = { reporting: CONNECTION_LABEL.connected, stale: CONNECTION_LABEL.stale, silent: CONNECTION_LABEL.offline, replay: "Replay" } as const;
const SOURCE_NOTE = {
  live: null,
  synthetic: "Synthetic host: generated by the simulator. These are not measurements of real infrastructure.",
  replay: "Replay host: stored history being replayed. Values are not current observations of live infrastructure.",
} as const;
const ALERT_LIMIT = 200;
const RESOLVED_SHOWN = 10;

/** Thresholds as the page uses them: configured values only. `status` says whether they could be loaded at all. */
type ThresholdState =
  | { status: "loading" }
  | { status: "error" }
  | { status: "loaded"; rules: NonNullable<MonitoringSettings["config"]["rules"]> };

function useThresholds(): ThresholdState {
  const q = useMonitoringSettings();
  if (q.data) return { status: "loaded", rules: q.data.config.rules };
  if (q.isError) return { status: "error" };
  return { status: "loading" };
}

export function HostDetailPage() {
  const { hostId = "" } = useParams();
  const [params] = useSearchParams();
  const host = useHost(hostId);
  const thresholds = useThresholds();
  // The list passes its own filtered URL as `from`; it is honoured only when it points back into the Hosts list.
  const from = params.get("from");
  const back = from && from.startsWith("/hosts") && !from.startsWith("//") ? from : `/hosts${globalSearch(params)}`;

  if (host.isPending) return (<><PageHeader title={hostId} /><Loading label="Loading host" /></>);
  if (!host.data) {
    const notFound = host.error instanceof ApiError && host.error.status === 404;
    return (
      <>
        <PageHeader title={hostId} actions={<Link className="btn" to={back}>All hosts</Link>} />
        {notFound ? <NeverReported hostId={hostId} /> : <ErrorState error={host.error} onRetry={() => host.refetch()} />}
      </>
    );
  }
  const h = host.data;

  return (
    <>
      <PageHeader title={h.hostname} subtitle={h.hostname !== h.host_id ? h.host_id : undefined} actions={<Link className="btn" to={back}>All hosts</Link>} />
      <StaleBanner failed={host.isError} updatedAt={host.dataUpdatedAt} onRetry={() => host.refetch()} />
      {SOURCE_NOTE[h.source] && <div className={`banner src-note src-note-${h.source}`} role="note"><SourceBadge source={h.source} /> {SOURCE_NOTE[h.source]}</div>}
      <div className="host-idbar" aria-label="Host summary">
        <HealthBadge status={h.health.status} />
        <SourceBadge source={h.source} />
        <span className="dim small">
          Service {h.service ?? <span className="mono">not reported</span>} · agent <span className="mono">{h.agent_id}</span> · last report {ago(h.last_seen_age_seconds)}
        </span>
      </div>
      <HostTabs carry={globalSearch(params)} />
      <OperationalState h={h} />
      <Current host={h} thresholds={thresholds} />
      <History host={h} thresholds={thresholds} />
      <HostAlerts host={h} carry={globalSearch(params)} />
      <Identity h={h} />
    </>
  );
}

